a = 10
b = 20

# Addition
sum = a + b
print(f"Sum of {a} and {b} is {sum}")

# Subtraction
difference = a - b
print(f"Difference of {a} and {b} is {difference}")

# Multiplication
product = a * b
print(f"Multiplication of {a} and {b} is {product}")

# Division
quotient = a / b
print(f"Division of {a} by {b} is {quotient}")

# Modulus
remainder = a % b
print(f"Remainder when {a} is divided by {b} is {remainder}")

# Floor Division
floor_division = a // b
print(f"Floor division of {a} by {b} is {floor_division}")

# Exponentiation
power = a ** b
print(f"{a} raised to the power of {b} is {power}")

# You can also perform operations with other data types, such as strings.
str1 = "Hello"
str2 = "World"
# Concatenation
concatenated_str = str1 + " " + str2
print(f"Concatenation of '{str1}' and '{str2}' is: '{concatenated_str}'")

# Repetition
repeated_str = str1 * 3
print(f"Repetition of '{str1}' three times is: '{repeated_str}'")

# You can also perform operations with boolean values.
bool1 = True   
bool2 = False
# Logical AND
and_result = bool1 and bool2
print(f"Logical AND of {bool1} and {bool2} is: {and_result}")
