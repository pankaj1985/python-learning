
#name is a variable that holds the string value "Pankaj".
name = "Pankaj"

#status is a variable that holds the boolean value True.
status = True

#marks is a variable that holds the floating-point value 85.5.
marks = 85.5

# You can print the value of a variable by using the print function.
print(f"The value of n is: {n}")

print(f"The value of name is : {name}")

print(f"The value of status is: {status}")   

print(f"The value of marks is: {marks}") 

#Displaying the type of variables using the type() function.
print(f"The type of n is: {type(n)}") # Output: <class 'int'>
print(f"The type of name is: {type(name)}") # Output: <class 'str'>
print(f"The type of status is: {type(status)}") # Output: <class 'bool'>
print(f"The type of marks is: {type(marks)}") # Output: <class 'float'>



# You can also reassign a variable to a different value or type.
n= "Hello" # Now n holds a string value instead of an integer.
print(n)    # Output: Hello


print(f"The value of n is now: {n} and its type is: {type(n)}")

